// Arcade layout: target = min(4K, largest 16:9 inside the swapchain);
// outRect = largest centred 16:9 rect of the swapchain (the target is scaled
// onto it by the composite's linear sample when the display is not 4K).
void arcadeLayout(Renderer& r) {
    const uint32_t sw = r.ctx.swapExtent.width, sh = r.ctx.swapExtent.height;
    uint32_t ow = sw, oh = (sw * 9) / 16;
    if (oh > sh) { oh = sh; ow = (sh * 16) / 9; }
    r.outRect.offset = {(int32_t)((sw - ow) / 2), (int32_t)((sh - oh) / 2)};
    r.outRect.extent = {ow, oh};
    uint32_t tw = ARCADE_W, th = ARCADE_H;
    if (ow < tw) { tw = ow; th = oh; }
    r.width = tw; r.height = th;
}

bool rendererCreate(Renderer& r, SDL_Window* window, int width, int height, bool validation, bool arcade,
                    StereoMode stereo, int eyeW, int eyeH) {
    // Stereo outranks arcade: the eye targets are the headset's (or the
    // dump's), never the cabinet's fixed 16:9 4K.
    if (stereo != STEREO_OFF) arcade = false;
    // ---- OpenXR, phase 1: loader + instance + system, BEFORE Vulkan, because
    // the runtime creates the Vulkan objects. No loader / runtime / headset
    // is not an error: the reason is printed and the game runs flat.
    vkctx::XrVkHooks hooks;
    if (stereo == STEREO_XR) {
        r.xrSession = new (std::nothrow) xr::Session();
        xr::Desc xd;
        xd.validation = validation;
        if (!r.xrSession || !xr::createInstance(*r.xrSession, xd)) {
            if (r.xrSession) { xr::destroy(*r.xrSession); delete r.xrSession; r.xrSession = nullptr; }
            std::fprintf(stderr, "[xr] --xr requested but unavailable: running flat\n");
            stereo = STEREO_OFF;
        } else {
            hooks.user = r.xrSession;
            hooks.createInstance = xr::hookCreateVkInstance;
            hooks.pickPhysicalDevice = xr::hookPickVkPhysicalDevice;
            hooks.createDevice = xr::hookCreateVkDevice;
        }
    }
    vkctx::Desc d;
    d.window = window;
    d.validation = validation;
    // FIFO paces the flat game at the display's rate (arcade mode adds
    // present_wait on top). Under OpenXR the HEADSET paces the frame
    // (xrWaitFrame, 90 Hz); the window is a mirror, and a FIFO mirror on a
    // 60 Hz monitor would throttle the headset to 60. MAILBOX (uncapped,
    // latest-wins) when the driver has it; createSwapchain falls back to FIFO
    // where it does not.
    d.presentMode = stereo == STEREO_XR ? VK_PRESENT_MODE_MAILBOX_KHR : VK_PRESENT_MODE_FIFO_KHR;
    d.presentWait = arcade;
    if (stereo == STEREO_XR) d.xr = &hooks;
    if (!vkctx::create(r.ctx, d)) return false;
    r.arcade = arcade && !r.ctx.headless;
    if (r.arcade) arcadeLayout(r);
    else if (!r.ctx.headless) {
        r.width = r.ctx.swapExtent.width; r.height = r.ctx.swapExtent.height;
        r.outRect = {{0, 0}, r.ctx.swapExtent};
    } else { r.width = (uint32_t)width; r.height = (uint32_t)height; r.outRect = {{0, 0}, {r.width, r.height}}; }
    r.viewCount = 1;
    r.viewMask = 0;
    r.stereoMode = stereo;
    r.xrMode = stereo != STEREO_OFF;
    if (stereo == STEREO_XR) {
        // ---- phase 2: the session, its reference space and the 2-layer
        // swapchain on the finished device. The render size is the EYE's.
        const VkFormat pref[2] = {VK_FORMAT_R8G8B8A8_SRGB, VK_FORMAT_B8G8R8A8_SRGB};
        if (!xr::createSession(*r.xrSession, r.ctx.instance, r.ctx.phys, r.ctx.device,
                               r.ctx.queueFamily, 0, pref, 2)) return false;
        r.width = r.xrSession->eyeWidth;
        r.height = r.xrSession->eyeHeight;
        r.xrFormat = r.xrSession->swapFormat;
        r.xrViews.assign(r.xrSession->images.size(), VK_NULL_HANDLE);
        for (size_t i = 0; i < r.xrSession->images.size(); ++i) {
            VkImageViewCreateInfo vci{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
            vci.image = r.xrSession->images[i];
            vci.viewType = VK_IMAGE_VIEW_TYPE_2D_ARRAY;
            vci.format = r.xrFormat;
            vci.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, xr::VIEW_COUNT};
            if (vkCreateImageView(r.ctx.device, &vci, nullptr, &r.xrViews[i]) != VK_SUCCESS) return false;
        }
    } else if (stereo == STEREO_HEADLESS) {
        r.width = (uint32_t)(eyeW > 0 ? eyeW : 1024);
        r.height = (uint32_t)(eyeH > 0 ? eyeH : 1024);
        r.xrFormat = VK_FORMAT_R8G8B8A8_SRGB;
        vkres::ImageDesc id;
        id.width = r.width; id.height = r.height; id.layers = xr::VIEW_COUNT;
        id.format = r.xrFormat;
        id.usage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT;
        if (!vkres::createImage(r.ctx, r.stereoDump, id)) return false;
    }
    if (stereo != STEREO_OFF) {
        if (r.ctx.maxMultiviewViews < xr::VIEW_COUNT) {
            std::fprintf(stderr, "[vk] device multiview count %u < 2\n", r.ctx.maxMultiviewViews);
            return false;
        }
        r.viewCount = xr::VIEW_COUNT;
        r.viewMask = 0b11;
        for (int v = 0; v < MAX_VIEWS; ++v) { r.rigs[v].proj = glm::mat4(1.0f); r.rigs[v].pose = glm::mat4(1.0f); }
    }
    // MSAA for the triangle edges (lines are SDF-antialiased regardless).
    {
        const VkSampleCountFlags ok = r.ctx.props.limits.framebufferColorSampleCounts & r.ctx.props.limits.framebufferDepthSampleCounts;
        r.sceneSamples = (ok & VK_SAMPLE_COUNT_4_BIT) ? VK_SAMPLE_COUNT_4_BIT : VK_SAMPLE_COUNT_1_BIT;
    }
    // Feedback-chamber storage: a NORMALIZED format when the device can blend
    // into one. The chamber's recurrence (rail_geometry.h FB_*) was tuned on
    // 8-bit targets, whose [0,1] clamp on every pass bounds the geometric
    // series; a float history has no such bound and the plume integrates
    // past white (vk_chamber.cpp, "THE STORAGE BOUND"). UNORM16 keeps the
    // clamp with a 1.5e-5 LSB, so the 8-bit residue sweep is still unneeded.
    {
        VkFormatProperties fp{};
        vkGetPhysicalDeviceFormatProperties(r.ctx.phys, VK_FORMAT_R16G16B16A16_UNORM, &fp);
        const VkFormatFeatureFlags need = VK_FORMAT_FEATURE_COLOR_ATTACHMENT_BLEND_BIT |
                                          VK_FORMAT_FEATURE_SAMPLED_IMAGE_FILTER_LINEAR_BIT;
        if ((fp.optimalTilingFeatures & need) == need) r.chamberFormat = VK_FORMAT_R16G16B16A16_UNORM;
    }
    if (!createPipelines(r)) return false;
    if (!createStaticResources(r)) return false;
    if (!postCreateTargets(r)) return false;
    r.starLastTime = 0.0;
    std::printf("[vk] renderer up: %ux%u%s, %s, MSAA x%d, texgen %u, chamber %u %s\n", r.width, r.height,
                r.viewCount > 1 ? " x2 views (multiview)" : "",
                r.stereoMode == STEREO_XR ? "openxr + mirror" : r.ctx.headless ? "headless" : "swapchain",
                (int)r.sceneSamples, TEXGEN_RES, CHAMBER_RES,
                r.chamberFormat == VK_FORMAT_R16G16B16A16_UNORM ? "unorm16" : "sfloat16");
    if (r.arcade)
        std::printf("[vk] arcade: fixed %ux%u target -> %ux%u output at (%d,%d) of a %ux%u swapchain, FIFO\n",
                    r.width, r.height, r.outRect.extent.width, r.outRect.extent.height,
                    r.outRect.offset.x, r.outRect.offset.y, r.ctx.swapExtent.width, r.ctx.swapExtent.height);
    return true;
}

void rendererDestroy(Renderer& r) {
    texMeanJoin();
    if (!r.ctx.device) return;
    vkctx::waitIdle(r.ctx);
    chamberDestroy(r, r.chamberTitle);
    chamberDestroy(r, r.chamberRail);
    chamberDestroy(r, r.chamberPause);
    chamberDestroy(r, r.chamberGameover);
    delete[] r.pauseSegBase; r.pauseSegBase = nullptr;
    delete[] r.pauseTriBase; r.pauseTriBase = nullptr;
    postDestroyTargets(r);
    destroyStaticResources(r);
    destroyPipelines(r);
    for (VkImageView v : r.xrViews) if (v) vkDestroyImageView(r.ctx.device, v, nullptr);
    r.xrViews.clear();
    vkres::destroyImage(r.ctx, r.stereoDump);
    // The session (and its swapchain images) goes before the device the
    // runtime created for it; the Vulkan objects are ours to destroy after.
    if (r.xrSession) { xr::destroy(*r.xrSession); delete r.xrSession; r.xrSession = nullptr; }
    vkctx::destroy(r.ctx);
}

// Re-size the targets after a swapchain recreate.
static bool handleResize(Renderer& r) {
    if (r.ctx.headless) return true;
    // In stereo the targets are the EYE's size; a mirror-window resize only
    // recreates the swapchain (vkctx does that) and the blit re-fits.
    if (r.stereoMode != STEREO_OFF) return true;
    if (r.arcade) {
        // Fixed target: only the output rect follows the swapchain; the
        // targets are rebuilt only if the display got too small for them.
        const uint32_t ow = r.width, oh = r.height;
        arcadeLayout(r);
        if (ow == r.width && oh == r.height) return true;
        vkctx::waitIdle(r.ctx);
        return postCreateTargets(r);
    }
    if (r.ctx.swapExtent.width == r.width && r.ctx.swapExtent.height == r.height) return true;
    vkctx::waitIdle(r.ctx);
    r.width = r.ctx.swapExtent.width;
    r.height = r.ctx.swapExtent.height;
    r.outRect = {{0, 0}, r.ctx.swapExtent};
    return postCreateTargets(r);
}

// ---- the frame bracket -------------------------------------------------------

bool frameBegin(Renderer& r, const GameEngine* engine, bool uiOnly) {
    (void)uiOnly;
    if (r.frameOpen) return true;
    // OpenXR paces the frame: events, then xrWaitFrame blocks to the
    // headset's display rate, then both views are located for the predicted
    // display time. A session that is not running (headset off, app in the
    // background) renders nothing and the loop keeps ticking.
    r.xrFrameOpen = false;
    if (r.stereoMode == STEREO_XR && r.xrSession) {
        xr::Session& s = *r.xrSession;
        xr::pollEvents(s);
        if (!xr::beginFrame(s)) {
            if (s.frameOpen) xr::endFrame(s, false);   // shouldRender == false: keep the pairing
            return false;
        }
        r.xrFrameOpen = true;
        for (uint32_t v = 0; v < xr::VIEW_COUNT; ++v) {
            xr::projectionFromFov(s.views[v].fov, 1.0f, 50.0f, &r.rigs[v].proj[0][0]);
            xr::viewFromPose(s.views[v].pose, XR_UNITS_PER_METRE, &r.rigs[v].pose[0][0]);
        }
    }
    VkCommandBuffer cmd = VK_NULL_HANDLE;
    // A minimised window or an out-of-date swapchain skips frames until the
    // swapchain is back; the game loop keeps ticking.
    bool ok = false;
    for (int attempt = 0; attempt < 2; ++attempt) {
        if (vkctx::beginFrame(r.ctx, cmd)) { ok = true; break; }
    }
    if (ok) ok = handleResize(r);
    if (!ok) {
        if (r.xrFrameOpen && r.xrSession) { xr::endFrame(*r.xrSession, false); r.xrFrameOpen = false; }
        return false;
    }
    r.cmd = cmd;
    r.ring = &r.rings[r.ctx.frameIndex];
    vkres::ringReset(*r.ring);
    fillUbo(r, engine);
    writeFrameUbo(r);
    r.frameOpen = true;
    r.sceneOpen = false;
    ++r.frameCounter;
    return true;
}

void sceneBegin(Renderer& r, const float clear[4]) {
    if (!r.frameOpen || r.sceneOpen) return;
    VkCommandBuffer cmd = r.cmd;
    const bool msaa = r.sceneSamples != VK_SAMPLE_COUNT_1_BIT;

    VkRenderingAttachmentInfo col{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
    col.imageView = msaa ? r.sceneMs.view : r.scene.view;
    col.imageLayout = msaa ? VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL : VK_IMAGE_LAYOUT_GENERAL;
    col.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
    col.storeOp = msaa ? VK_ATTACHMENT_STORE_OP_DONT_CARE : VK_ATTACHMENT_STORE_OP_STORE;
    for (int i = 0; i < 4; ++i) col.clearValue.color.float32[i] = clear[i];
    if (msaa) {
        col.resolveMode = VK_RESOLVE_MODE_AVERAGE_BIT;
        col.resolveImageView = r.scene.view;
        col.resolveImageLayout = VK_IMAGE_LAYOUT_GENERAL;
    }
    VkRenderingAttachmentInfo dep{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
    dep.imageView = r.sceneDepth.view;
    dep.imageLayout = VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL;
    dep.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
    dep.storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
    dep.clearValue.depthStencil = {1.0f, 0};

    VkRenderingInfo ri{VK_STRUCTURE_TYPE_RENDERING_INFO};
    ri.renderArea = {{0, 0}, {r.width, r.height}};
    ri.layerCount = r.viewMask ? 1 : r.viewCount;
    ri.viewMask = r.viewMask;
    ri.colorAttachmentCount = 1;
    ri.pColorAttachments = &col;
    ri.pDepthAttachment = &dep;
    vkCmdBeginRendering(cmd, &ri);
    r.sceneOpen = true;
}

void sceneEnd(Renderer& r) {
    if (!r.sceneOpen) return;
    vkCmdEndRendering(r.cmd);
    r.sceneOpen = false;
}

void frameEnd(Renderer& r, float flashEnv, const float flashRgb[3]) {
    if (!r.frameOpen) return;
    sceneEnd(r);
    postRun(r, flashEnv, flashRgb, r.fade);
    vkctx::endFrame(r.ctx);
    // The headset's image is released AFTER the submit that wrote it, then
    // the projection layer (both views) goes to the compositor.
    if (r.xrFrameOpen && r.xrSession) { xr::endFrame(*r.xrSession, true); r.xrFrameOpen = false; }
    r.frameOpen = false;
    r.cmd = VK_NULL_HANDLE;
    r.ring = nullptr;
}

