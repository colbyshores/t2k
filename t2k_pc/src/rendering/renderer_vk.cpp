void ts_ui_mark_textured_span(TsRenderer rr) {
    Renderer* r = asRenderer(rr);
    if (!r || !r->uiOpen) return;
    r->uiTexturedSpanEnd = r->uiTris.count;
}

void ts_render_ui_begin(TsRenderer rr) {
    Renderer* r = asRenderer(rr);
    if (!r) return;
    if (!frameBegin(*r, nullptr, true)) return;
    // Generate the UI slot's skin for the level the caller will preview.
    if (r->uiTubeTexLevel >= 0)
        texgenRun(*r, r->texgen[1], r->uiTubeTexLevel % GRID_NUM_TEX, (float)r->frameCounter / 60.0f, 0.0f, false);
    uiBegin(*r, UI_CLEAR);
}

void ts_render_ui_end(TsRenderer rr) {
    Renderer* r = asRenderer(rr);
    if (!r || !r->frameOpen) return;
    uiEnd(*r);
    const float white[3] = {1.0f, 1.0f, 1.0f};
    frameEnd(*r, 0.0f, white);
}

void ts_render_title_begin(TsRenderer rr, GameEngine& engine) {
    Renderer* r = asRenderer(rr);
    if (!r) return;
    if (!frameBegin(*r, &engine, true)) return;
    drawTitleLogo(*r, engine);       // opens the scene pass itself (chamber first)
    segStreamBegin(*r, r->uiSegs, 32768);
    triStreamBegin(*r, r->uiTris, 65536);
    r->uiTexturedSpanEnd = -1;
    r->uiOpen = true;
    r->uiTitle = true;
    fontSetTarget(r, &r->uiSegs, &r->uiTris);
}

void ts_render_title_end(TsRenderer rr) {
    Renderer* r = asRenderer(rr);
    if (!r || !r->frameOpen) return;
    uiEnd(*r);
    r->uiTitle = false;
    const float white[3] = {1.0f, 1.0f, 1.0f};
    frameEnd(*r, 0.0f, white);
}

