VkDescriptorSet allocTexSet(Renderer& r, VkDescriptorSetLayout layout,
                            VkImageView v0, VkSampler s0, VkImageView v1, VkSampler s1) {
    VkDescriptorSetAllocateInfo ai{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
    ai.descriptorPool = r.descPool;
    ai.descriptorSetCount = 1;
    ai.pSetLayouts = &layout;
    VkDescriptorSet set = VK_NULL_HANDLE;
    if (vkAllocateDescriptorSets(r.ctx.device, &ai, &set) != VK_SUCCESS) {
        std::fprintf(stderr, "[vk] descriptor pool exhausted\n");
        return VK_NULL_HANDLE;
    }
    updateTexSet(r, set, v0, s0, v1, s1);
    return set;
}

void updateTexSet(Renderer& r, VkDescriptorSet set, VkImageView v0, VkSampler s0,
                  VkImageView v1, VkSampler s1) {
    VkDescriptorImageInfo ii[2]{};
    ii[0] = {s0, v0, VK_IMAGE_LAYOUT_GENERAL};
    ii[1] = {s1, v1, VK_IMAGE_LAYOUT_GENERAL};
    VkWriteDescriptorSet w[2]{};
    uint32_t n = 0;
    for (uint32_t i = 0; i < 2; ++i) {
        if (ii[i].imageView == VK_NULL_HANDLE) continue;
        w[n].sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
        w[n].dstSet = set;
        w[n].dstBinding = i;
        w[n].descriptorCount = 1;
        w[n].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        w[n].pImageInfo = &ii[i];
        ++n;
    }
    if (n) vkUpdateDescriptorSets(r.ctx.device, n, w, 0, nullptr);
}

void bindFrameSet(Renderer& r, VkPipelineLayout layout) {
    const uint32_t dyn = (uint32_t)r.frameUboOffset[r.ctx.frameIndex];
    vkCmdBindDescriptorSets(r.cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, layout, 0, 1,
                            &r.frameSets[r.ctx.frameIndex], 1, &dyn);
}

