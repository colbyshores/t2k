// ---- projection helpers (Vulkan clip conventions: y down, z in [0,1]) ------

// perspective(fovY, aspect, near, far) in the GAME's law (glm::perspective,
// right-handed, camera looks down -Z), then flipped for Vulkan's y-down NDC
// and remapped to the [0,1] depth range. Built by hand rather than through
// glm so no GLM_FORCE_* macro can differ between this TU and the core's.
static glm::mat4 perspectiveVk(float fovYDeg, float aspect, float n, float f) {
    const float t = std::tan(fovYDeg * 0.5f * 3.14159265358979f / 180.0f);
    glm::mat4 m(0.0f);
    m[0][0] = 1.0f / (aspect * t);
    m[1][1] = -1.0f / t;                 // y flip
    m[2][2] = f / (n - f);
    m[2][3] = -1.0f;
    m[3][2] = -(f * n) / (f - n);
    return m;
}

// The game's UI ortho box, 0..1.3333 x 0..1.0 with y UP, to Vulkan clip.
static glm::mat4 orthoUiVk() {
    glm::mat4 m(1.0f);
    m[0][0] = 2.0f / 1.3333f;  m[3][0] = -1.0f;
    m[1][1] = -2.0f;           m[3][1] = 1.0f;     // y up in UI, down in clip
    m[2][2] = 0.0f;            m[3][2] = 0.5f;     // z: constant, inside [0,1]
    return m;
}

glm::mat4 uiOrthoMatrix() { return orthoUiVk(); }

// The UI box on a seat-locked plane in stereo (UI_PLANE_DEPTH_M /
// UI_PLANE_HEIGHT_M): UI (x, y, z) -> seat-space (metres * units-per-metre),
// centred ahead of the seat, z of the UI vertex ignored exactly as the
// ortho box ignores it. Composed with the eye rig it becomes uiProj[v].
static glm::mat4 uiPlaneMatrix() {
    const float S = UI_PLANE_HEIGHT_M * XR_UNITS_PER_METRE;
    glm::mat4 m(0.0f);
    m[0][0] = S;
    m[1][1] = S;
    m[3][0] = -0.66665f * S;
    m[3][1] = -0.5f * S;
    m[3][2] = -UI_PLANE_DEPTH_M * XR_UNITS_PER_METRE;
    m[3][3] = 1.0f;
    return m;
}

// The game's VIEW law, identical on both existing backends (GL translateWorld
// / C3D buildView): multiplier wobble, game-over spiral, then the eye.
static glm::mat4 viewMatrix(const GameEngine& e) {
    glm::mat4 v(1.0f);
    const float PI = 3.14159265358979f;
    if (e.player.multiplier < 1.125f) {
        const float amp = 1.125f - e.player.multiplier;
        // Exact integer turns (game/phase.h) -- the parity twin of
        // renderer_c3d.cpp buildView. THIS is the build an arcade cabinet runs,
        // so it is the one that actually sits at multi-week uptimes where
        // `(float)e.time` stops resolving milliseconds and the whole view
        // matrix starts wobbling in visible steps.
        const float ang = ts::phase::sinTurns(ts::phase::at((uint32_t)e.time, K_MULT_WOBBLE))
                        * amp * amp * 60.0f;
        v = glm::rotate(v, glm::radians(ang), glm::vec3(0.1f, 0.1f, 1.0f));
    }
    if (e.player.gameover_animation > 10) {
        const float g = (e.player.gameover_animation - 10) * 0.01f;
        const float s = g * g;
        v = glm::scale(v, glm::vec3(1.0f - s * 0.25f, 1.0f - s * 0.25f, 1.0f + s));
        const float ang = ts::fastSin((float)(e.player.gameover_animation - 10) * PI * 0.0075f) * 120.0f;
        v = glm::rotate(v, glm::radians(ang), glm::vec3(0.1f, 0.1f, 1.0f));
    }
    const Vec3 eye = camera_eye(e);
    v = glm::translate(v, glm::vec3(-eye.x, -eye.y, -eye.z));
    return v;
}

