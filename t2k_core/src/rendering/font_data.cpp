// ============================================================================
// Character Mapping
// ============================================================================

int charToIndex(char ch) {
    int c = (int)(unsigned char)ch;
    if (c >= 65 && c <= 90) return c - 65;       // A-Z
    if (c >= 97 && c <= 122) return c - 97;       // a-z (same as uppercase)
    if (c >= 48 && c <= 57) return c - 22;        // 0-9: '0'=26 .. '9'=35
    if (c == 33) return 36;                       // !
    if (c == 34 || c == 94 || c == 96) return 39; // " ^ ` -> apostrophe
    if (c == 58) return 49;                       // :
    if (c == 59) return 44;                       // ; -> comma
    if (c == 63) return 37;                       // ?
    if (c == 60 || c == 91 || c == 123) return 40; // < [ { -> left paren
    if (c == 92) return 38;                       // backslash
    if (c == 95) return 50;                       // _
    if (c == 124) return 48;                      // |
    if (c == 62 || c == 93 || c == 125) return 41; // > ] } -> right paren
    if (c == 126) return 45;                      // ~ -> dash
    if (c >= 39 && c <= 47) return c;             // '()*+,-./ -> direct mapping
    return -1;                                    // Space or unknown
}
